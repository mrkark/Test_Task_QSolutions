#!/usr/bin/env bash
set -e

echo "======================================================================"
echo "  QSolutions: Интерактивная запись экрана человеком (проверка F5 зума)"
echo "======================================================================"

REC_NAME="Operator_Zoom_Test"
REC_URL="https://duckduckgo.com"

read -p "Введите название записи/компании (по умолчанию: $REC_NAME): " user_name
if [ -n "$user_name" ]; then
    REC_NAME="$user_name"
fi

read -p "Введите начальный URL (по умолчанию: $REC_URL): " user_url
if [ -n "$user_url" ]; then
    REC_URL="$user_url"
fi

echo ""
echo "[*] Запуск браузера для записи..."
echo "[*] В открывшемся окне нажимайте F5 (или экранную кнопку [Zoom (F5)]) для зума к курсору."
echo "[*] Чтобы завершить запись, просто закройте окно браузера или нажмите Enter здесь."
echo ""

python3 record_interactive.py --name "$REC_NAME" --url "$REC_URL"

echo ""
echo "======================================================================"
echo "Запись завершена! Все файлы сохранены в папке ./video"
echo "======================================================================"
